use std::fmt::Debug;

use crate::model::Date;

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum Label<'a> {
    Language,
    Heading,
    Folder(&'a str),
    Videos(usize),
    Done(usize),
    TooManyCount(usize),
    FailedCount(usize),
    UnfinishedCount(usize),
    WaitingCount(usize),
    Tracks(usize),
    Reminder,
    ExpandAll,
    CollapseAll,
    Computed(Date),
    Tried(Date),
    Length(u64),
    NotAnalysed(u64),
    FailedBadge,
    TooManyBadge,
    UnfinishedBadge,
    OlderBadge,
    WaitingBadge,
    Failure {
        video: &'a str,
        cause: &'a str,
        place: &'a str,
    },
    Todo {
        cause: &'a str,
        folder: &'a str,
    },
    Detail(&'a str),
    RefusedCount(usize),
    RefusedHeading(usize),
    RefusedWhen(Date),
    RefusedConsequence(usize),
    RefusedInput {
        path: &'a str,
        reason: &'a str,
        cause: Option<&'a str>,
        videos: &'a str,
    },
    PreviousResults,
    UnfinishedText,
    OlderText,
    WaitingText,
    TooMany {
        video: &'a str,
        count: usize,
        limit: usize,
    },
    TooManyTodo,
    SummaryAlt {
        video: &'a str,
        tracks: usize,
    },
    PartAlt {
        video: &'a str,
        part: usize,
        parts: usize,
        first: usize,
        last: usize,
    },
    Part,
    Parts(&'a str),
    PartTab {
        part: usize,
        parts: usize,
        first: usize,
        last: usize,
    },
    ColumnTrack,
    ColumnStart,
    ColumnLength,
    ColumnVerdict,
    ColumnWatch,
    TableCaption(&'a str),
    NoVerdict,
    Clip,
    Zoom,
    PlayClip(usize),
    PlayZoom(usize),
    ShowTrack(usize),
    Playing {
        track: usize,
        total: usize,
        start: &'a str,
        zoom: bool,
    },
    Unreadable,
    Back,
    Previous,
    Next,
    PreviousClip,
    NextClip,
    Player(&'a str),
    TableLink,
    AnnotatedLink,
    Start(f64),
    Seconds(f64),
}

pub trait Labels: Debug {
    fn label(&self, label: &Label<'_>) -> String;
}
